#!/usr/bin/env python3
"""Draws the app's launcher icon: a small keyboard lit in the note colours.

One description of the shapes is written out twice: as the Android vector drawables
the app uses, and as an SVG picture for looking at (as a circle and as a rounded
square, large and small, on light and dark). To change the icon, change it here.

    python3 tools/make_icon.py app/src/main/res /tmp/icon-preview.svg
    qlmanage -t -s 800 -o /tmp /tmp/icon-preview.svg     # macOS: makes a PNG of the preview
"""
import sys, pathlib
res, preview = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])

WHITE = ["E53935", "FB8C00", "FDD835", "43A047", "1E88E5", "8E24AA", "F06292"]      # C D E F G A B
BLACK = {0: "F4511E", 1: "FFB300", 3: "00ACC1", 4: "3949AB", 5: "D81B60"}           # after white key n

def mix(hex_color, other, amount):
    a = [int(hex_color[i:i + 2], 16) for i in (0, 2, 4)]; b = [int(other[i:i + 2], 16) for i in (0, 2, 4)]
    return "".join(f"{round(x + (y - x) * amount):02X}" for x, y in zip(a, b))

# Geometry in the 108 x 108 adaptive-icon canvas; only the middle 66 is always visible.
BODY = (26.0, 34.5, 82.0, 73.5); BODY_R = 7.0
KEY_W, GAP = 6.9, 0.5
keys_w = 7 * KEY_W + 6 * GAP
KX = 54 - keys_w / 2; KTOP, KBOT = 37.8, 70.2
BLACK_W, BLACK_BOT = 4.3, KTOP + 19.0

def rrect(x1, y1, x2, y2, r):
    return (f"M{x1 + r:.2f},{y1:.2f} L{x2 - r:.2f},{y1:.2f} Q{x2:.2f},{y1:.2f} {x2:.2f},{y1 + r:.2f} "
            f"L{x2:.2f},{y2 - r:.2f} Q{x2:.2f},{y2:.2f} {x2 - r:.2f},{y2:.2f} L{x1 + r:.2f},{y2:.2f} "
            f"Q{x1:.2f},{y2:.2f} {x1:.2f},{y2 - r:.2f} L{x1:.2f},{y1 + r:.2f} Q{x1:.2f},{y1:.2f} {x1 + r:.2f},{y1:.2f} Z")

def bottom_round(x1, y1, x2, y2, r):  # square at the top, rounded at the bottom
    return (f"M{x1:.2f},{y1:.2f} L{x2:.2f},{y1:.2f} L{x2:.2f},{y2 - r:.2f} Q{x2:.2f},{y2:.2f} {x2 - r:.2f},{y2:.2f} "
            f"L{x1 + r:.2f},{y2:.2f} Q{x1:.2f},{y2:.2f} {x1:.2f},{y2 - r:.2f} Z")

white_keys = [(KX + i * (KEY_W + GAP), KX + i * (KEY_W + GAP) + KEY_W, WHITE[i]) for i in range(7)]
black_keys = [(white_keys[i][1] + GAP / 2 - BLACK_W / 2, white_keys[i][1] + GAP / 2 + BLACK_W / 2, c) for i, c in BLACK.items()]

# ---------- Android vector drawables ----------
HEAD = ('<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tools/make_icon.py; change it there. {note} -->\n'
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n    xmlns:aapt="http://schemas.android.com/aapt"\n'
        '    android:width="108dp"\n    android:height="108dp"\n    android:viewportWidth="108"\n    android:viewportHeight="108">\n')

def path(d, fill=None, gradient=None, stroke=None, stroke_w=None):
    out = f'    <path android:pathData="{d}"'
    if fill: out += f'\n        android:fillColor="#{fill}"'
    if stroke: out += f'\n        android:strokeColor="#{stroke}"\n        android:strokeWidth="{stroke_w}"'
    if not gradient: return out + " />\n"
    kind, a, b, c0, c1 = gradient
    if kind == "linear":
        g = f'android:type="linear" android:startX="{a[0]}" android:startY="{a[1]}" android:endX="{b[0]}" android:endY="{b[1]}"'
    else:
        g = f'android:type="radial" android:centerX="{a[0]}" android:centerY="{a[1]}" android:gradientRadius="{b}"'
    return (out + ">\n        <aapt:attr name=\"android:fillColor\">\n"
            f"            <gradient {g}\n                android:startColor=\"#{c0}\" android:endColor=\"#{c1}\" />\n"
            "        </aapt:attr>\n    </path>\n")

bg = HEAD.format(note="The app's violet backdrop with a glow where the keyboard sits")
bg += path("M0,0h108v108h-108z", gradient=("linear", (0, 0), (108, 108), "FF34277A", "FF0C0D1A"))
bg += path("M0,0h108v108h-108z", gradient=("radial", (54, 56), 46, "A07C6CFF", "007C6CFF"))
bg += "</vector>\n"

fg = HEAD.format(note="A small keyboard lit in the note colours (music/NoteColors.kt)")
fg += path(rrect(*BODY, BODY_R), fill="FF090A12", stroke="FF4A4F78", stroke_w="1")
for x1, x2, c in white_keys:
    fg += path(bottom_round(x1, KTOP, x2, KBOT, 1.6), gradient=("linear", (x1, KTOP), (x1, KBOT), "FF" + mix(c, "FFFFFF", 0.5), "FF" + c))
for x1, x2, c in black_keys:
    fg += path(bottom_round(x1, KTOP, x2, BLACK_BOT, 1.2), fill="FF0D0E1A")
    fg += path(rrect(x1 + 0.9, BLACK_BOT - 5.2, x2 - 0.9, BLACK_BOT - 1.2, 0.8), fill="FF" + c)
fg += "</vector>\n"

# One colour only (themed icons): the white keys with the black keys cut out of them.
mono = HEAD.format(note="The same keyboard in one colour, for themed icons")
mono += path(rrect(*BODY, BODY_R), stroke="FFFFFFFF", stroke_w="2.2")
for i, (x1, x2, _) in enumerate(white_keys):
    left = BLACK_W / 2 if (i - 1) in BLACK else 0.0
    right = BLACK_W / 2 if i in BLACK else 0.0
    m = 0.55  # a little air around each black key
    d = (f"M{x1 + (left + m if left else 0):.2f},{KTOP:.2f} L{x2 - (right + m if right else 0):.2f},{KTOP:.2f} "
         + (f"L{x2 - right - m:.2f},{BLACK_BOT + m:.2f} L{x2:.2f},{BLACK_BOT + m:.2f} " if right else "")
         + f"L{x2:.2f},{KBOT - 1.6:.2f} Q{x2:.2f},{KBOT:.2f} {x2 - 1.6:.2f},{KBOT:.2f} L{x1 + 1.6:.2f},{KBOT:.2f} "
         + f"Q{x1:.2f},{KBOT:.2f} {x1:.2f},{KBOT - 1.6:.2f} "
         + (f"L{x1:.2f},{BLACK_BOT + m:.2f} L{x1 + left + m:.2f},{BLACK_BOT + m:.2f} " if left else "") + "Z")
    mono += path(d, fill="FFFFFFFF")
mono += "</vector>\n"

(res / "drawable/ic_launcher_background.xml").write_text(bg)
(res / "drawable/ic_launcher_foreground.xml").write_text(fg)
(res / "drawable/ic_launcher_monochrome.xml").write_text(mono)
adaptive = ('<?xml version="1.0" encoding="utf-8"?>\n<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
            '    <background android:drawable="@drawable/ic_launcher_background" />\n'
            '    <foreground android:drawable="@drawable/ic_launcher_foreground" />\n'
            '    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />\n</adaptive-icon>\n')
(res / "mipmap-anydpi-v26/ic_launcher.xml").write_text(adaptive)
(res / "mipmap-anydpi-v26/ic_launcher_round.xml").write_text(adaptive)

# ---------- SVG preview: as a circle, as a rounded square, and small ----------
defs, art = [], []
defs.append('<linearGradient id="bg" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="#34277A"/><stop offset="1" stop-color="#0C0D1A"/></linearGradient>')
defs.append('<radialGradient id="glow" gradientUnits="userSpaceOnUse" cx="54" cy="56" r="46"><stop offset="0" stop-color="#7C6CFF" stop-opacity="0.63"/><stop offset="1" stop-color="#7C6CFF" stop-opacity="0"/></radialGradient>')
art.append('<rect width="108" height="108" fill="url(#bg)"/><rect width="108" height="108" fill="url(#glow)"/>')
art.append(f'<path d="{rrect(*BODY, BODY_R)}" fill="#090A12" stroke="#4A4F78" stroke-width="1"/>')
for i, (x1, x2, c) in enumerate(white_keys):
    defs.append(f'<linearGradient id="k{i}" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="#{mix(c, "FFFFFF", 0.5)}"/><stop offset="1" stop-color="#{c}"/></linearGradient>')
    art.append(f'<path d="{bottom_round(x1, KTOP, x2, KBOT, 1.6)}" fill="url(#k{i})"/>')
for x1, x2, c in black_keys:
    art.append(f'<path d="{bottom_round(x1, KTOP, x2, BLACK_BOT, 1.2)}" fill="#0D0E1A"/>')
    art.append(f'<path d="{rrect(x1 + 0.9, BLACK_BOT - 5.2, x2 - 0.9, BLACK_BOT - 1.2, 0.8)}" fill="#{c}"/>')
icon = "".join(art)
# What launchers show is the middle 72 of the 108 canvas, cut to their own shape.
def shown(x, y, scale, clip):
    return f'<g transform="translate({x},{y}) scale({scale}) translate(-18,-18)" clip-path="url(#{clip})">{icon}</g>'
svg = ('<svg xmlns="http://www.w3.org/2000/svg" width="800" height="800" viewBox="0 0 800 800">'
       f'<defs>{"".join(defs)}<clipPath id="circle"><circle cx="54" cy="54" r="36"/></clipPath>'
       '<clipPath id="squircle"><rect x="18" y="18" width="72" height="72" rx="20"/></clipPath></defs>'
       '<rect width="800" height="800" fill="#D8DCE6"/><rect y="560" width="800" height="240" fill="#101018"/>'
       + shown(20, 20, 5, "circle") + shown(420, 20, 5, "squircle")
       + shown(30, 410, 1.5, "squircle") + shown(170, 410, 1.5, "circle") + shown(320, 420, 1.0, "squircle")
       + shown(420, 420, 1.0, "circle") + shown(520, 430, 0.67, "squircle") + shown(590, 430, 0.67, "circle")
       + shown(30, 600, 1.5, "squircle") + shown(170, 600, 1.5, "circle") + shown(320, 610, 1.0, "squircle")
       + shown(420, 610, 1.0, "circle") + shown(520, 620, 0.67, "squircle") + shown(590, 620, 0.67, "circle")
       + '</svg>')
preview.write_text(svg)
print("written")
